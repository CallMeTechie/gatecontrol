'use strict';

// "Namen im VPN" behind a REAL dnsmasq: a conf as entrypoint.sh writes it,
// the block of services/vpnNames.js in it, the hosts file of services/dns.js
// next to it — asked over the network like a VPN device does.
//
// Needs dnsmasq. Without it the file is skipped — unless
// GC_TEST_DNSMASQ=required (CI installs dnsmasq-base).

const { describe, it, before, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const dgram = require('node:dgram');
const { Resolver } = require('node:dns').promises;
const { spawn, spawnSync } = require('node:child_process');

const { setup, teardown } = require('./helpers/setup');

const REQUIRED = process.env.GC_TEST_DNSMASQ === 'required';
const hasDnsmasq = spawnSync('dnsmasq', ['--version']).status === 0;
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gc-vpn-names-dnsmasq-'));
const confPath = path.join(dir, 'dnsmasq.conf');
process.env.GC_DNSMASQ_CONF = confPath;
process.on('exit', () => { try { fs.rmSync(dir, { recursive: true, force: true }); } catch { /* ignore */ } });

function freePort() {
  return new Promise((resolve) => {
    const s = dgram.createSocket('udp4');
    s.bind(0, '127.0.0.1', () => { const p = s.address().port; s.close(() => resolve(p)); });
  });
}
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

describe('Namen im VPN behind a real dnsmasq', { skip: !hasDnsmasq && !REQUIRED ? 'dnsmasq not installed' : false }, () => {
  let db; let vpnNames; let dns; let config; let port; let upstream; let child = null; let realRestart;
  const forwarded = [];

  let stopping = false;
  // supervised like in the image (scripts/wg-wrapper.sh): whoever ends dnsmasq —
  // this test or a `pkill dnsmasq` of another test file running next to it —
  // it comes back with the conf as it is now
  function start() {
    const c = spawn('dnsmasq', ['--keep-in-foreground', `--user=${os.userInfo().username}`, '--pid-file=', `--conf-file=${confPath}`], { stdio: 'ignore' });
    c.once('exit', () => { if (!stopping && child === c) start(); });
    child = c;
  }
  async function restart() {
    const old = child;
    await new Promise((r) => { old.once('exit', r); old.kill('SIGTERM'); });
    await answering();
  }
  function resolver() {
    const r = new Resolver({ timeout: 1000, tries: 1 });
    r.setServers([`127.0.0.1:${port}`]);
    return r;
  }
  // structural wait: until dnsmasq answers its own fixed name
  async function answering() {
    for (let i = 0; i < 100; i++) {
      try { await resolver().resolve4(`gateway.${config.dns.domain}`); return; } catch { await sleep(50); }
    }
    throw new Error('dnsmasq does not answer');
  }
  const ask = (name) => resolver().resolve4(name);
  const code = (name) => ask(name).then(() => 'ok', (e) => e.code);

  before(async () => {
    assert.ok(hasDnsmasq, 'GC_TEST_DNSMASQ=required but dnsmasq is not installed');
    await setup();
    db = require('../src/db/connection').getDb();
    vpnNames = require('../src/services/vpnNames');
    dns = require('../src/services/dns');
    config = require('../config/default');
    fs.mkdirSync(path.dirname(config.dns.hostsFile), { recursive: true });
    port = await freePort();
    const upPort = await freePort();
    // the "internet": notes every name that leaves dnsmasq, answers nothing
    upstream = dgram.createSocket('udp4');
    upstream.on('message', (msg) => {
      const labels = [];
      for (let i = 12; msg[i]; i += msg[i] + 1) labels.push(msg.subarray(i + 1, i + 1 + msg[i]).toString());
      forwarded.push(labels.join('.').toLowerCase());
    });
    await new Promise((r) => upstream.bind(upPort, '127.0.0.1', r));

    db.prepare('DELETE FROM peers').run();
    db.prepare('DELETE FROM routes').run();
    db.prepare("INSERT INTO domains (domain, status) VALUES ('example.com', 'verified')").run();
    db.prepare("INSERT INTO peers (name, public_key, allowed_ips, hostname, hostname_source) VALUES ('buero', 'pk-buero', '10.8.0.10/32', 'laptop-buero', 'admin')").run();
    db.prepare("INSERT INTO routes (domain, target_ip, target_port, enabled, route_type) VALUES ('nas.example.com', '10.0.0.1', 8080, 1, 'http')").run();

    // the lines of entrypoint.sh (interface lines replaced by a local port)
    const gw = config.wireguard.gatewayIp;
    const zone = config.dns.domain;
    fs.writeFileSync(confPath, [
      '# Auto-generated by entrypoint.sh — do not edit manually.',
      `port=${port}`, 'listen-address=127.0.0.1', 'bind-interfaces',
      'no-resolv', 'no-hosts', 'cache-size=1000',
      `local=/${zone}/`, `domain=${zone}`, 'domain-needed', 'bogus-priv',
      `addn-hosts=${config.dns.hostsFile}`,
      `host-record=gateway.${zone},${gw}`, `host-record=server.${zone},${gw}`, `host-record=gc-server.${zone},${gw}`,
      `server=127.0.0.1#${upPort}`,
      '',
    ].join('\n'));
    dns.rebuildNow();
    start();
    await answering();
    // restartDnsmasq() is synchronous in the service; the test waits for the respawn itself
    realRestart = dns.restartDnsmasq;
    dns.restartDnsmasq = () => {};
  });

  after(async () => {
    if (realRestart) dns.restartDnsmasq = realRestart;
    stopping = true;
    if (child) child.kill('SIGKILL');
    if (upstream) upstream.close();
    teardown();
  });

  it('as today: the device and the fixed names in the legacy zone', async () => {
    assert.deepEqual(await ask(`laptop-buero.${config.dns.domain}`), ['10.8.0.10']);
    assert.deepEqual(await ask(`gateway.${config.dns.domain}`), [config.wireguard.gatewayIp]);
  });

  it('an own domain: both spellings answer, the fixed names in both zones, routes point inwards', async () => {
    const r = vpnNames.save('example.com', 'vpn');
    assert.equal(r.ok, true);
    assert.equal(r.restarted, true);
    await restart();
    assert.deepEqual(await ask('laptop-buero.vpn.example.com'), ['10.8.0.10']);
    assert.deepEqual(await ask(`laptop-buero.${config.dns.domain}`), ['10.8.0.10']);
    for (const n of ['gateway', 'server', 'gc-server']) {
      assert.deepEqual(await ask(`${n}.vpn.example.com`), [config.wireguard.gatewayIp], n);
      assert.deepEqual(await ask(`${n}.${config.dns.domain}`), [config.wireguard.gatewayIp], n);
    }
    assert.deepEqual(await ask('nas.example.com'), [config.wireguard.gatewayIp]);
    assert.deepEqual(await ask(`home.${config.dns.domain}`), [config.wireguard.gatewayIp]);
  });

  it('the server answers the zone alone: an unknown name is "does not exist", nothing goes to the internet', async () => {
    forwarded.length = 0;
    assert.equal(await code('gibt-es-nicht.vpn.example.com'), 'ENOTFOUND');
    assert.equal(await code(`gibt-es-nicht.${config.dns.domain}`), 'ENOTFOUND');
    assert.deepEqual(forwarded, []);
    // … while the rest of the domain still goes upstream (the mock does not answer)
    assert.notEqual(await code('mail.example.com'), 'ok');
    assert.deepEqual([...new Set(forwarded)], ['mail.example.com']);
  });

  it('a new device name needs no restart (hosts file + SIGHUP)', async () => {
    db.prepare("INSERT INTO peers (name, public_key, allowed_ips, hostname, hostname_source) VALUES ('pixel', 'pk-pixel', '10.8.0.14/32', 'pixel-8', 'agent')").run();
    dns.rebuildNow();
    child.kill('SIGHUP');
    let got = null;
    for (let i = 0; i < 100 && !got; i++) { got = await ask('pixel-8.vpn.example.com').catch(() => null); if (!got) await sleep(50); }
    assert.deepEqual(got, ['10.8.0.14']);
  });

  it('back to the default: the legacy zone goes on, the other one is no longer answered here', async () => {
    assert.equal(vpnNames.save('', '').restarted, true);
    await restart();
    assert.deepEqual(await ask(`laptop-buero.${config.dns.domain}`), ['10.8.0.10']);
    forwarded.length = 0;
    assert.notEqual(await code('laptop-buero.vpn.example.com'), 'ok');
    assert.ok(forwarded.includes('laptop-buero.vpn.example.com'), 'not a local zone any more');
  });
});
